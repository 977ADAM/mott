"""Нормализация текста чеченских источников.

Что делает: схлопывает пробелы и убирает пробел перед знаком препинания.
Что НЕ делает: не трогает кавычки.

Про кавычки. Ранее в SPEC было записано, что `"` в Коране — «повреждение текста».
Это неверно: `"` — обычная кавычка (прямая речь, названия). Непарные числа объясняются
разбиением по аятам — речь открывается в одном стихе и закрывается в другом
(1028 открытий после ':', 1007 закрытий в конце строки).

Попытка убрать пробелы ВНУТРИ кавычек провалилась дважды:

  1. Первая версия срезала пробел перед ЛЮБОЙ кавычкой и превращала законное
     `элира: "Ас...` в `элира:"Ас...`.
  2. Вторая версия чинила только парные кавычки, но строки часто НАЧИНАЮТСЯ с
     закрывающей кавычки (речь из предыдущего аята), из-за чего пары сдвигались
     на единицу и пробел перед открывающей кавычкой снова срезался:
     `тешо тоьшалла дира: " Цуьнан...` -> `дира:" Цуьнан...`.

Отличить открывающую кавычку от закрывающей в этой разметке однозначно нельзя,
поэтому обработка кавычек убрана совсем. Косметический выигрыш не стоит риска
испортить 2,4 % строк. Если понадобится — делать отдельно и с проверкой носителем.
"""

from __future__ import annotations

import re

_MULTISPACE_RE = re.compile(r"\s+")

# Пробел перед знаком препинания: "гуш ," -> "гуш,". Кавычки здесь нет намеренно.
_SPACE_BEFORE_PUNCT_RE = re.compile(r"\s+([,.;:!?])")


def clean(text: str) -> str:
    """Безопасная нормализация: только пробелы и пробел перед пунктуацией."""
    if not text:
        return ""
    out = _MULTISPACE_RE.sub(" ", text)
    out = _SPACE_BEFORE_PUNCT_RE.sub(r"\1", out)
    return out.strip()


def normalize_whitespace(text: str) -> str:
    return _MULTISPACE_RE.sub(" ", text or "").strip()


# Артефакты, которые мы СОЗНАТЕЛЬНО не чиним (см. докстринг выше).
UNFIXED = {
    'пробел после открывающей "': r'"\s+',
    "пробел перед закрывающей \"": r'\s+"',
}


def artifact_rates(texts) -> dict[str, float]:
    """Доли строк с артефактами — для отчёта до/после."""
    import pandas as pd

    s = pd.Series(list(texts)).fillna("")
    n = max(len(s), 1)
    rates = {
        "двойной пробел": r"\S  \S",
        "пробел перед ,": r"\s,",
        "пробел перед .": r"\s\.",
    }
    out = {k: s.str.contains(v, regex=True).sum() / n * 100 for k, v in rates.items()}
    for k, v in UNFIXED.items():
        out[f"{k} (не чиним)"] = s.str.contains(v, regex=True).sum() / n * 100
    return out
